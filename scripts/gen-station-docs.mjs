// Generates docs/stations/<ID>.md profile pages from src/lib data modules.
// Compiles the TS modules to a temp dir (CommonJS), requires them, writes markdown.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

execSync('npx tsc src/lib/aqi.ts src/lib/data.ts --outDir .tmp-gen --module commonjs --target es2020 --moduleResolution node --skipLibCheck', { stdio: 'inherit' });
// package.json has "type": "module", so rename the compiled output to .cjs
{ const { renameSync, readFileSync, writeFileSync: wf } = await import('node:fs'); renameSync('.tmp-gen/data.js', '.tmp-gen/data.cjs'); renameSync('.tmp-gen/aqi.js', '.tmp-gen/aqi.cjs'); wf('.tmp-gen/data.cjs', readFileSync('.tmp-gen/data.cjs', 'utf8').replace('require("./aqi")', 'require("./aqi.cjs")')); }

const { COMPUTED, CURRENT_MONTH } = await import('../.tmp-gen/data.cjs');

function categoryOf(aqi) {
  if (aqi <= 50) return 'Good';
  if (aqi <= 100) return 'Satisfactory';
  if (aqi <= 200) return 'Moderate';
  if (aqi <= 300) return 'Poor';
  if (aqi <= 400) return 'Very Poor';
  return 'Severe';
}

mkdirSync('docs/stations', { recursive: true });

for (const { station, aqi, baseline } of COMPUTED) {
  const cat = categoryOf(aqi.value);
  const sep = baseline.monthly.find((m) => m.month === CURRENT_MONTH);
  const seasonal = baseline.monthly.map((m) => `| ${String(m.month + 1).padStart(2, '0')} | ${m.medianAqi} | ${m.p25}–${m.p75} |`).join('\n');
  const pollutants = aqi.subIndexes.map((s) => `| ${s.name} | ${s.concentration} ${s.unit} | ${s.index} |`).join('\n');
  const content = `# ${station.city} — ${station.station}

**Station ID:** ${station.id}
**District:** ${station.district}, ${station.state}
**Coordinates:** ${station.lat}, ${station.lng}
**Latest observation:** ${station.updated}
**Source:** ${station.sourceKind === 'MODEL' ? 'Open-Meteo modelled estimate' : station.sourceDetail}

## Latest AQI

| Metric | Value |
| --- | --- |
| AQI | **${aqi.value}** |
| Category | ${cat} |
| Dominant pollutant | ${aqi.dominant ?? '—'} |

## Pollutant sub-profile

| Pollutant | Concentration | Sub-index |
| --- | --- | --- |
${pollutants}

## Baseline (12 months)

| Metric | Value |
| --- | --- |
| Median AQI | ${baseline.medianAqi} |
| Typical range (p25–p75) | ${baseline.p25}–${baseline.p75} |
| September median | ${sep?.medianAqi ?? '—'} |
| September range | ${sep ? sep.p25 + '–' + sep.p75 : '—'} |

### Monthly medians

| Month | Median | Typical range |
| --- | --- | --- |
${seasonal}

## Weather context

| Metric | Value |
| --- | --- |
| Temperature | ${station.temp} °C |
| Humidity | ${station.humidity} % |
| Wind | ${station.wind} km/h ${station.windDir} |

---
*Generated by \`scripts/gen-station-docs.mjs\` · AQI method: CPCB India breakpoints · Reference: CPCB All India AQI Dashboard*
`;
  writeFileSync(`docs/stations/${station.id}.md`, content);
}

rmSync('.tmp-gen', { recursive: true, force: true });
console.log(`Generated ${COMPUTED.length} station profiles in docs/stations/`);
